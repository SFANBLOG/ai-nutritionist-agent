# ------------------------------------------------------------------ 构建单个 persona
def build(raw: dict, idx: int) -> dict:
    s = SCENARIOS[raw["scn"]]
    core_keys = ["空腹血糖(FPG)", "尿酸(UA)", "总胆固醇(TC)", "甘油三酯(TG)"]
    lab = {k: LAB_ITEMS[k][2] for k in core_keys}
    lab.update(s.get("lab", {}))
    lab.update(raw.get("lab") or {})

    glu = float(lab.get("空腹血糖(FPG)", LAB_ITEMS["空腹血糖(FPG)"][2]))
    ua = float(lab.get("尿酸(UA)", LAB_ITEMS["尿酸(UA)"][2]))
    tc = float(lab.get("总胆固醇(TC)", LAB_ITEMS["总胆固醇(TC)"][2]))
    tg = float(lab.get("甘油三酯(TG)", LAB_ITEMS["甘油三酯(TG)"][2]))
    bmi_v = float(bmi(str(raw["h"]), str(raw["w"])))

    vals = {"glu": glu, "ua": ua, "tc": tc, "tg": tg,
            "sys": raw["sys"], "dia": raw["dia"], "bmi": bmi_v,
            "name": raw["name"], "age": raw["age"], "sex": raw["sex"]}

    def fmt(items):
        return [t.format(**vals) for t in items]

    return {
        "name": raw["name"], "sex": raw["sex"], "age": raw["age"],
        "no": f"20260913{idx:03d}",
        "phone": f"138****{6000 + idx:04d}",
        "job": raw.get("job") or "职工",
        "marriage": raw.get("marriage") or "已婚",
        "past": raw.get("past") or s.get("past", ""),
        "habit": raw.get("habit") or s.get("habit", ""),
        "family": raw.get("family") or s.get("family", ""),
        "height": str(raw["h"]), "weight": str(raw["w"]),
        "waist": str(raw["waist"]), "hip": str(raw["hip"]), "pulse": str(raw["pulse"]),
        "sys": raw["sys"], "dia": raw["dia"],
        "lab": lab,
        "depts": s["depts"], "imaging": s["imaging"],
        "conclusion": fmt(s["conclusion"]),
        "advice": fmt(s["advice"]),
        "recheck": fmt(s["recheck"]),
        "doctor": s["doctor"], "reviewer": s["reviewer"], "package": s["package"],
        "file": f"report_{idx:02d}_{raw['name']}_{raw['sex']}{raw['age']}_{raw.get('tag') or s.get('tag', '')}.txt",
    }


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for i, raw in enumerate(PERSONAS, 1):
        p = build(raw, i)
        text = render(p)
        path = OUT_DIR / p["file"]
        path.write_text(text, encoding="utf-8", newline="\r\n")
        print(f"[OK] {path.name}  ({len(text.splitlines())} 行)")
    print(f"\n共生成 {len(PERSONAS)} 份报告 → {OUT_DIR}")


if __name__ == "__main__":
    main()
