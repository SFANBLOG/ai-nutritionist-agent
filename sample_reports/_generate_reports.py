def _w(text: str) -> int:
    """显示宽度估算(中文占 2)"""
    return sum(2 if ord(c) > 127 else 1 for c in text)


def lab_row(name: str, value: str, flag: str = "") -> str:
    """化验单行。

    格式:`项目名 | 结果 | 单位 | 参考范围`
    —— 用 `|` 分隔而非宽空格对齐,是为了让「项目名」与「结果」之间始终只有 3 个字符,
       满足解析正则 `[^\\d]{0,12}` 的间隔上限(宽空格对齐会撑到 20+ 字符导致解析失败)。
    """
    unit, ref, _ = LAB_ITEMS[name]
    v = f"{value} {flag}".strip()
    vcell = v + " " * max(1, 10 - _w(v))
    ucell = unit + " " * max(1, 10 - _w(unit))
    return f"  {name} | {vcell}| {ucell}| {ref}"


