def bmi(height_cm: str, weight_kg: str) -> str:
    h = float(height_cm) / 100
    return f"{float(weight_kg) / (h * h):.1f}"


def flag_of(name: str, value: str) -> str:
    """按参考范围给 ↑ / ↓ 标记(仅用于展示,不参与解析)"""
    unit, ref, _ = LAB_ITEMS[name]
    if "~" not in ref or value in ("阴性",):
        return ""
    lo, hi = [float(x.strip()) for x in ref.split("~")]
    try:
        v = float(value)
    except ValueError:
        return ""
    if v > hi:
        return "↑"
    if v < lo:
        return "↓"
    return ""


def render(p: dict) -> str:
    L = 78
    lines: list[str] = []

    def rule(ch: str = "─") -> str:
        return ch * L

    def ctr(text: str) -> str:
        pad = (L - sum(2 if ord(c) > 127 else 1 for c in text)) // 2
        return " " * max(0, pad) + text

    lines.append(rule("═"))
    lines.append(ctr("滨海市第一人民医院(三级甲等)"))
    lines.append(ctr("健康管理中心 · 健康体检报告"))
    lines.append(rule("═"))
    lines.append(f"报告编号:TJ{p['no']}            体检日期:2026-09-12")
    lines.append(f"体检类型:{p['package']}")
    lines.append(f"报告日期:2026-09-13            打印时间:2026-09-13 09:20")
    lines.append("")

    lines.append("一、受检者基本信息")
    lines.append(rule())
    lines.append(f"  姓    名:{p['name']}              性  别:{p['sex']}")
    lines.append(f"  年    龄:{p['age']} 岁                 体检号:{p['no']}")
    lines.append(f"  联系电话:{p['phone']}          职  业:{p['job']}")
    lines.append(f"  婚姻状况:{p['marriage']}               民  族:汉")
    lines.append(f"  既往病史:{p['past']}")
    lines.append(f"  个人史 :{p['habit']}")
    lines.append(f"  家族史 :{p['family']}")
    lines.append("")

    lines.append("二、一般检查")
